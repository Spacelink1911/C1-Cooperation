uint8_t IR_Protocol_CRC8(const uint8_t *data, size_t length)
{
    uint8_t crc = 0u;
    size_t i;
    uint8_t bit;

    if (data == NULL) {
        return 0u;
    }

    for (i = 0u; i < length; ++i) {
        crc ^= data[i];
        for (bit = 0u; bit < 8u; ++bit) {
            if ((crc & 0x80u) != 0u) {
                crc = (uint8_t)((uint8_t)(crc << 1) ^ 0x07u);
            } else {
                crc = (uint8_t)(crc << 1);
            }
        }
    }
    return crc;
}
